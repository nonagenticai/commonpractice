// src/lib/i18n/direction.test.ts — `dirFor()` answers for EVERY shipped locale, and `RTL_LOCALES`
// can never name a locale the catalogs no longer have.
//
// ⛔ THE DEFECT THIS FILE EXISTS FOR. `direction.ts` is the SINGLE source both halves of the render
// read: `src/hooks.server.ts` stamps `<html dir>` from it in Node, and `$lib/stores/locale.svelte.ts`
// re-applies it in the browser. Its own header explains why it is not a const in the store — this
// repo has already been bitten by two hardcoded `['ar','he']` lists, one updated and one not, with
// no test comparing them. Collapsing them to one module removes the SERVER/BROWSER drift but not the
// other one: `RTL_LOCALES` is still a hand-written set sitting next to a GENERATED locale list.
//
// The two directions that drift can go, and which test below catches each:
//
//  • **A locale is ADDED to `messages/` and not classified.** `dirFor()` has no failure mode for an
//    unknown tag — it returns `'ltr'`, matching `baseLocale`, which is the right default for a lookup
//    and the wrong one for a decision. A ninth locale that happened to be Farsi or Urdu would ship
//    with `dir="ltr"` and NOTHING would be red: every existing assertion still passes, the catalog
//    tests only compare key sets, and the mismatch is invisible to a sighted LTR reviewer (which is
//    the exact blind spot `hooks.server.ts` documents for the bug it fixes). The `locales.length`
//    anchor is what forces a human to open this file and make the call consciously.
//  • **A locale is REMOVED from the catalogs and left in `RTL_LOCALES`.** Nothing throws; the set
//    just carries a tag no reader can ever hold, and the next person to read it believes the product
//    ships a locale it does not. The SUBSET assertion is the half that reddens.
//
// ⚠️ WHY PER-LOCALE AND NOT A BLOB. `expect([...RTL_LOCALES]).toEqual(['ar','he'])` would pass while
// `dirFor('ar')` returned `'ltr'` — the set and the FUNCTION are two things, and it is the function
// the shell calls. Every locale is asserted by name, through `dirFor`, so the failure message says
// which locale and which direction rather than printing two arrays.
import { describe, it, expect } from 'vitest';
import { locales } from '$lib/paraglide/runtime';
import { RTL_LOCALES, isRtl, dirFor, isSupportedLocale } from './direction';

/** The RTL half, by name. Adding a locale here without adding it to `RTL_LOCALES` reddens below. */
const RTL = ['ar', 'he'] as const;
/** The LTR half, by name — spelled out rather than derived, so a wrong `RTL_LOCALES` cannot define
 *  its own complement and make both halves agree with each other about the same mistake. */
const LTR = ['en', 'nl', 'pl', 'fr', 'es', 'de'] as const;

describe('direction is decided for every locale the product ships', () => {
	// ⛔ THE DRIFT GUARD — the most important assertion in this file. `RTL_LOCALES` is hand-written
	// and `locales` is generated by the paraglide compiler from `messages/*.json`, so the two can only
	// be kept honest by comparison. This is the direction that produces a SILENT lie: a tag in
	// `RTL_LOCALES` that no longer exists in the catalogs never reaches `isRtl`, so no rendering test
	// can see it, and the set stays wrong until someone reads it and believes it.
	it('⛔ every member of RTL_LOCALES is a locale paraglide actually compiles', () => {
		const supported = locales as readonly string[];
		for (const rtl of RTL_LOCALES) {
			expect(
				supported,
				`RTL_LOCALES names "${rtl}", which is not in the compiled paraglide locale list ` +
					`[${supported.join(', ')}] — either the catalog was deleted and this set was not, ` +
					`or the tag is a typo that has been silently doing nothing.`
			).toContain(rtl);
		}
	});

	it('⛔ the catalog ships exactly eight locales', () => {
		// ⚠️ THIS ANCHOR IS THE POINT, not bookkeeping. `dirFor()` returns `'ltr'` for anything it does
		// not recognise, so a NINTH locale needs no code change to ship — it just ships left-to-right.
		// If that ninth locale is written right-to-left (fa, ur, he variants, ckb) the entire chrome
		// paints mirrored-wrong at first paint and assistive technology is told the wrong thing, which
		// is precisely the defect `src/hooks.server.ts` was written to remove. Whoever adds locale nine
		// must come here, classify its direction CONSCIOUSLY, and only then move this number — the
		// conflict on this line is the feature.
		expect(locales).toHaveLength(8);
		expect([...locales].sort()).toEqual([...RTL, ...LTR].sort());
	});

	it('every compiled locale gets exactly "rtl" or "ltr" — never undefined', () => {
		// The total-function property. `dirFor` is typed `'rtl' | 'ltr'`, but it is called from
		// `transformPageChunk` where its return value goes straight into an HTML attribute: a
		// `undefined` would ship `dir="undefined"`, which browsers treat as `dir="ltr"` while
		// invalidating the document. Asserted at runtime because the type says nothing about a locale
		// list that grew after the type was written.
		for (const locale of locales) {
			expect(['rtl', 'ltr'], `dirFor(${locale}) is not a legal dir value`).toContain(dirFor(locale));
		}
	});

	for (const locale of RTL) {
		it(`${locale} is right-to-left`, () => {
			expect(isRtl(locale), `${locale} must be RTL`).toBe(true);
			expect(dirFor(locale), `<html dir> for ${locale}`).toBe('rtl');
			expect(RTL_LOCALES.has(locale)).toBe(true);
		});
	}

	for (const locale of LTR) {
		it(`${locale} is left-to-right`, () => {
			// ⚠️ The negative half is not decoration. `dirFor` defaults to `'ltr'`, so the RTL cases
			// above would still pass if `RTL_LOCALES` held all eight and `isRtl` were inverted. These
			// six are what make "ar is rtl" mean "ar and ONLY ar/he are rtl".
			expect(isRtl(locale), `${locale} must be LTR`).toBe(false);
			expect(dirFor(locale), `<html dir> for ${locale}`).toBe('ltr');
			expect(RTL_LOCALES.has(locale)).toBe(false);
		});
	}
});

describe('isRtl refuses to treat an absent locale as a direction', () => {
	// The shell resolver can hand `dirFor` a value that came from a cookie, i.e. anything at all. Each
	// of these is a DIFFERENT absence and they reach the function by different routes: `undefined` is
	// `cookies.get()` on a first visit, `null` is a cleared cookie, `''` is a cookie that was written
	// empty by a failed `pgSetLocale`, and `'xx'` is a tag from a client the product does not support.
	// A `Set.has(undefined)` is false anyway — what is pinned here is that none of them THROWS on the
	// server, because a hook that throws serves a 500 instead of a page with the wrong `dir`.
	it.each([
		['null', null],
		['undefined', undefined],
		['the empty string', ''],
		['an unsupported tag', 'xx']
	])('isRtl(%s) is false and dirFor is "ltr"', (_label, value) => {
		expect(isRtl(value)).toBe(false);
		expect(dirFor(value)).toBe('ltr');
	});
});

describe('isSupportedLocale is the only supported-locale source', () => {
	it('accepts every compiled locale', () => {
		// NON-VACUITY: if this loop read an empty `locales` it would assert nothing, which is the
		// failure shape a generated import invites. The length anchor above is the other half.
		expect(locales.length).toBeGreaterThan(0);
		for (const locale of locales) {
			expect(isSupportedLocale(locale), `${locale} must be supported`).toBe(true);
		}
	});

	it.each([
		['an unsupported tag', 'xx'],
		['a region-qualified tag', 'nl-BE'],
		['the empty string', ''],
		['null', null],
		['undefined', undefined]
	])('rejects %s', (_label, value) => {
		// ⚠️ `nl-BE` is REJECTED on purpose and that is not a bug: this guard tests membership of the
		// compiled list, and reducing a region subtag to its base is the negotiator's job in
		// `hooks.server.ts`, not this predicate's. Pinned here so a future "helpful" fuzzy match cannot
		// land silently — it would make the cookie arm accept values the client runtime cannot resolve.
		expect(isSupportedLocale(value)).toBe(false);
	});
});
